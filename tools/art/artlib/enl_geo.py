def inside(lon, lat, poly):
    """Even-odd point-in-polygon for arrays of points (degrees)."""
    poly = np.asarray(poly, dtype=np.float64)
    x0, y0 = poly[:, 0], poly[:, 1]
    x1, y1 = np.roll(x0, -1), np.roll(y0, -1)
    out = np.zeros(lon.shape, dtype=bool)
    for a, b, c, d in zip(x0, y0, x1, y1):
        cond = (b > lat) != (d > lat)
        xs = a + (lat - b) * (c - a) / np.where(d - b == 0, 1e-9, d - b)
        out ^= cond & (lon < xs)
    return out


def land_index(lon, lat):
    """-1 = sea, else the tint class of the land under (lon, lat)."""
    out = np.full(lon.shape, -1, dtype=np.int64)
    for name, poly in LAND.items():
        m = inside(lon, lat, poly)
        out[m] = TINT[name]
    for poly in WATER.values():
        out[inside(lon, lat, poly)] = -1
    ant = lat < -69.0 + 2.5 * np.sin(np.radians(lon) * 2.0) + 1.5 * np.sin(np.radians(lon) * 5.0 + 1.0)
    out[ant] = 3
    return out


