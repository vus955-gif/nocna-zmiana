def glyph(ch):
    """Bitmap (11 x 5 bool) of one character; unknown characters are blank."""
    return _GLYPHS.get(ch, _GLYPHS[" "])


def line_bitmap(text, spacing=1):
    """Bitmap (11 x width) of one line of text, ``spacing`` blank columns
    between letters."""
    if not text:
        return np.zeros((CELL_H, 1), dtype=bool)
    step = CELL_W + spacing
    out = np.zeros((CELL_H, step * len(text) - spacing), dtype=bool)
    for i, ch in enumerate(text):
        out[:, i * step:i * step + CELL_W] = glyph(ch)
    return out


def width_px(text, spacing=1):
    return line_bitmap(text, spacing).shape[1]


def text_mask(u, v, text, center_u, base_v, px, spacing=1, align="center"):
    """Boolean mask of the texels (u, v in metres) covered by ``text``.
    ``px`` = size of one font pixel in metres, ``base_v`` = baseline (the
    bottom of the capitals), ``center_u`` = horizontal anchor (centre, or the
    left / right end with align="left" / "right")."""
    bmp = line_bitmap(text, spacing)
    h, w = bmp.shape
    if align == "center":
        left = center_u - w * px * 0.5
    elif align == "left":
        left = center_u
    else:
        left = center_u - w * px
    top = base_v + (BASE_ROW + 1) * px
    col = np.floor((u - left) / px + 1e-6).astype(np.int64)
    row = np.floor((top - v) / px + 1e-6).astype(np.int64)
    inside = (col >= 0) & (col < w) & (row >= 0) & (row < h)
    out = np.zeros(len(u), dtype=bool)
    out[inside] = bmp[row[inside], col[inside]]
    return out


def fit_px(text, width_m, texel, max_px=None, spacing=1):
    """Largest font pixel (a whole number of texels) that fits ``text`` into
    ``width_m`` metres."""
    w = width_px(text, spacing)
    k = max(1, int(width_m / (w * texel)))
    px = k * texel
    if max_px is not None:
        px = min(px, max(texel, int(max_px / texel) * texel))
    return px
